<?php

namespace App\Http\Controllers\Api\V1;

use App\Http\Controllers\Controller;
use App\Models\DailyQrToken;
use App\Models\Presensi;
use Carbon\Carbon;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Validator;

class PresensiController extends Controller
{
    /**
     * POST /api/v1/presensi/scan
     * Validate Admin-generated QR code, verify SMK Telkom Purwokerto geofence, and process scoring.
     */
    public function scan(Request $request): JsonResponse
    {
        if ($request->user()->role === 'orang_tua') {
            return response()->json([
                'success' => false,
                'message' => 'Akun Orang Tua hanya dapat memantau aktivitas anak dan tidak dapat melakukan presensi QR.',
            ], 403);
        }

        $validator = Validator::make($request->all(), [
            'qr_token' => 'required|string',
            'latitude' => 'required|numeric|between:-90,90',
            'longitude' => 'required|numeric|between:-180,180',
        ], [
            'qr_token.required' => 'Kode QR dari Admin tidak boleh kosong.',
            'latitude.required' => 'Lokasi GPS wajib aktif untuk memastikan presensi di kawasan SMK Telkom Purwokerto.',
            'longitude.required' => 'Lokasi GPS wajib aktif untuk memastikan presensi di kawasan SMK Telkom Purwokerto.',
        ]);

        if ($validator->fails()) {
            return response()->json([
                'success' => false,
                'message' => $validator->errors()->first() ?: 'Validasi gagal.',
                'errors' => $validator->errors(),
            ], 422);
        }

        // 1. Verify student physical location against SMK Telkom Purwokerto geofence
        $schoolConfig = config('hadir.school');
        $schoolName = $schoolConfig['name'] ?? 'SMK Telkom Purwokerto';
        $schoolLat = (float) ($schoolConfig['latitude'] ?? -7.435210);
        $schoolLng = (float) ($schoolConfig['longitude'] ?? 109.249210);
        $maxRadius = (float) ($schoolConfig['radius_meters'] ?? 150);

        $userLat = (float) $request->input('latitude');
        $userLng = (float) $request->input('longitude');
        $distanceMeters = $this->calculateDistanceMeters($userLat, $userLng, $schoolLat, $schoolLng);
        $roundedDistance = (int) round($distanceMeters);

        if ($distanceMeters > $maxRadius) {
            return response()->json([
                'success' => false,
                'message' => "Presensi ditolak! Anda berada di luar kawasan {$schoolName} (jarak {$roundedDistance} m, batas maksimal " . (int) $maxRadius . " m dari sekolah).",
                'data' => [
                    'jarak_meter' => $roundedDistance,
                    'radius_maksimal_meter' => (int) $maxRadius,
                    'lokasi_sekolah' => $schoolName,
                ],
            ], 403);
        }

        $user = $request->user();

        // Parse token if scanned from JSON QR payload generated by Admin Filament panel
        $rawToken = trim($request->qr_token);
        $extractedToken = $rawToken;

        if (str_starts_with($rawToken, '{') && str_ends_with($rawToken, '}')) {
            $parsed = json_decode($rawToken, true);
            if (is_array($parsed) && isset($parsed['token'])) {
                $extractedToken = trim((string) $parsed['token']);
            }
        }

        $now = Carbon::now('Asia/Jakarta');
        $today = $now->toDateString();
        $currentTime = $now->format('H:i:s');

        // 2. Strictly validate against active QR token created by Admin for today (no demo token bypass)
        $dailyToken = DailyQrToken::where('tanggal', $today)->first();
        if (!$dailyToken || $extractedToken === '' || !hash_equals($dailyToken->token, $extractedToken)) {
            return response()->json([
                'success' => false,
                'message' => 'Kode QR tidak valid, bukan buatan Admin, atau sudah kedaluwarsa untuk hari ini.',
            ], 400);
        }

        // 3. Process Datang (check-in) or Pulang (check-out)
        $presensi = Presensi::where('user_id', $user->id)
            ->where('tanggal', $today)
            ->first();

        if (!$presensi) {
            $deadlineHi = config('hadir.attendance.check_in_deadline', '07:00');
            $batasTepatWaktu = strlen($deadlineHi) === 5 ? $deadlineHi . ':00' : $deadlineHi;
            $isTepatWaktu = ($currentTime <= $batasTepatWaktu);

            $status = $isTepatWaktu ? 'Tepat Waktu' : 'Terlambat';
            $poinPerubahan = $isTepatWaktu ? 0 : -5;

            if (!$isTepatWaktu) {
                $user->poin_kedisiplinan = max(0, $user->poin_kedisiplinan - 5);
                $user->recalculateBintang();
            }

            $presensi = Presensi::create([
                'user_id' => $user->id,
                'tanggal' => $today,
                'jam_datang' => $currentTime,
                'jam_pulang' => null,
                'status' => $status,
                'poin_perubahan' => $poinPerubahan,
            ]);

            return response()->json([
                'success' => true,
                'message' => $isTepatWaktu
                    ? "Presensi Datang Berhasil di kawasan {$schoolName}! Anda hadir Tepat Waktu."
                    : "Presensi Datang tercatat di kawasan {$schoolName} (Terlambat). Poin kedisiplinan berkurang -5.",
                'data' => [
                    'tipe_scan' => 'datang',
                    'tanggal' => $today,
                    'jam_datang' => substr($currentTime, 0, 5) . ' WIB',
                    'jam_pulang' => null,
                    'status' => $status,
                    'poin_perubahan' => $poinPerubahan,
                    'sisa_poin' => $user->poin_kedisiplinan,
                    'bintang' => (float) $user->bintang,
                    'jarak_meter' => $roundedDistance,
                    'lokasi_sekolah' => $schoolName,
                    'pesan' => $isTepatWaktu
                        ? 'Pertahankan kedisiplinan Anda untuk meraih rating bintang 5.0!'
                        : 'Usahakan datang sebelum pukul 07:00 WIB di hari berikutnya untuk menjaga rapor PKL tetap prima.',
                ],
            ], 200);
        }

        if ($presensi->jam_pulang !== null) {
            return response()->json([
                'success' => false,
                'message' => 'Anda sudah menyelesaikan presensi datang dan pulang untuk hari ini.',
                'data' => [
                    'jam_datang' => substr($presensi->jam_datang, 0, 5) . ' WIB',
                    'jam_pulang' => substr($presensi->jam_pulang, 0, 5) . ' WIB',
                    'status' => $presensi->status,
                ],
            ], 422);
        }

        $presensi->update([
            'jam_pulang' => $currentTime,
        ]);

        return response()->json([
            'success' => true,
            'message' => "Presensi Pulang Berhasil di kawasan {$schoolName}! Hati-hati di jalan.",
            'data' => [
                'tipe_scan' => 'pulang',
                'tanggal' => $today,
                'jam_datang' => substr($presensi->jam_datang, 0, 5) . ' WIB',
                'jam_pulang' => substr($currentTime, 0, 5) . ' WIB',
                'status' => $presensi->status,
                'poin_perubahan' => $presensi->poin_perubahan,
                'sisa_poin' => $user->poin_kedisiplinan,
                'bintang' => (float) $user->bintang,
                'jarak_meter' => $roundedDistance,
                'lokasi_sekolah' => $schoolName,
            ],
        ], 200);
    }

    /**
     * GET /api/v1/presensi/today
     * Return student's attendance today alongside official SMK Telkom Purwokerto geofence configuration.
     */
    public function today(Request $request): JsonResponse
    {
        $user = $request->user();
        $subject = $user->resolvedStudent();
        $today = Carbon::now('Asia/Jakarta')->toDateString();

        $presensi = Presensi::where('user_id', $subject->id)
            ->where('tanggal', $today)
            ->first();

        $riwayatTerbaru = Presensi::where('user_id', $subject->id)
            ->orderBy('tanggal', 'desc')
            ->limit(10)
            ->get()
            ->map(fn (Presensi $item) => [
                'tanggal' => $item->tanggal?->toDateString(),
                'tanggal_label' => $item->tanggal ? Carbon::parse($item->tanggal)->isoFormat('ddd, D MMM Y') : '-',
                'jam_datang' => $item->jam_datang ? substr($item->jam_datang, 0, 5) . ' WIB' : null,
                'jam_pulang' => $item->jam_pulang ? substr($item->jam_pulang, 0, 5) . ' WIB' : null,
                'status' => $item->status,
                'poin_perubahan' => $item->poin_perubahan,
            ]);

        return response()->json([
            'success' => true,
            'message' => 'Data presensi hari ini berhasil diambil.',
            'data' => [
                'sudah_presensi' => $presensi !== null,
                'tanggal' => $today,
                'jam_datang' => $presensi?->jam_datang ? substr($presensi->jam_datang, 0, 5) . ' WIB' : null,
                'jam_pulang' => $presensi?->jam_pulang ? substr($presensi->jam_pulang, 0, 5) . ' WIB' : null,
                'status' => $presensi?->status ?? 'Belum Hadir',
                'poin_perubahan' => $presensi?->poin_perubahan ?? 0,
                'anak' => [
                    'nis_nip' => $subject->nis_nip,
                    'nama_lengkap' => $subject->nama_lengkap,
                    'kelas' => $subject->kelas,
                ],
                'riwayat_terbaru' => $riwayatTerbaru,
                'school_geofence' => config('hadir.school'),
            ],
        ], 200);
    }

    /**
     * Calculate Haversine distance in meters between two WGS84 GPS coordinates.
     */
    private function calculateDistanceMeters(float $lat1, float $lon1, float $lat2, float $lon2): float
    {
        $earthRadius = 6371000.0;
        $dLat = deg2rad($lat2 - $lat1);
        $dLon = deg2rad($lon2 - $lon1);

        $a = sin($dLat / 2) * sin($dLat / 2)
            + cos(deg2rad($lat1)) * cos(deg2rad($lat2))
            * sin($dLon / 2) * sin($dLon / 2);
        $c = 2 * atan2(sqrt($a), sqrt(1 - $a));

        return $earthRadius * $c;
    }
}
